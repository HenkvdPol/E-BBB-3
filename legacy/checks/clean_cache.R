## Run from anywhere:  Rscript checks/clean_cache.R   (paths are relative to this file)
check_dir <- local({ f <- sub("^--file=", "", grep("^--file=", commandArgs(FALSE), value = TRUE))
  if (length(f)) dirname(normalizePath(f[1])) else getwd() })
out_dir <- file.path(check_dir, "output"); dir.create(out_dir, showWarnings = FALSE)
source(file.path(check_dir, "load_settings.R"))
runs <- complete_runs(settings); keep <- character()
for (i in seq_len(nrow(runs))) keep <- c(keep, names(needed_banks(complete_settings(settings, runs[i, ]))))
files <- list.files(settings$sim$bank_dir); drop <- setdiff(files, paste0(unique(keep), ".rds"))
cat("needed:", length(unique(keep)), " present:", length(files), " missing:", length(setdiff(paste0(unique(keep), ".rds"), files)), " removed (not used any more):", length(drop), "\n")
unlink(file.path(settings$sim$bank_dir, drop))
